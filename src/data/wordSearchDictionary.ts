/**
 * Normaliza una palabra a mayúsculas y caracteres estándar A-Z sin tildes ni caracteres especiales
 */
function cleanWord(w: string): string {
  return w
    .toUpperCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/Ñ/g, 'N')
    .replace(/[^A-Z]/g, '');
}

